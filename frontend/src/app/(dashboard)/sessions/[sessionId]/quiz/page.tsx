function downloadQuizPDF(questions: QuizQuestion[], subject: string, grade: string, language: string) {
  const langNote = language !== "english" ? ` · ${language.charAt(0).toUpperCase() + language.slice(1)}` : "";
  const items = questions.map((q, i) => {
    const isTrue = q.type === "true_false";
    const opts = isTrue
      ? `<div class="options"><span class="opt ${q.correct === true ? "correct" : ""}">A. True</span><span class="opt ${q.correct === false ? "correct" : ""}">B. False</span></div>`
      : (q.options ?? []).map((opt, j) => `<div class="opt ${j === q.correct ? "correct" : ""}">${String.fromCharCode(65+j)}. ${opt}</div>`).join("");
    return `<div class="question"><div class="q-header"><span class="q-num">${i+1}</span><span class="q-text">${q.text}</span><span class="badge">${q.bloom_level ?? ""}</span></div><div class="options">${opts}</div></div>`;
  }).join("");

  const html = `<!DOCTYPE html><html><head><meta charset="UTF-8"/><title>Quiz${langNote}</title>
<style>
  @import url('https://fonts.googleapis.com/css2?family=Noto+Sans:wght@400;600;700&family=Noto+Sans+Devanagari:wght@400;600;700&family=Noto+Sans+Kannada:wght@400;600;700&family=Noto+Sans+Telugu:wght@400;600;700&family=Noto+Sans+Tamil:wght@400;600;700&display=swap');
  body{font-family:'Noto Sans',Arial,sans-serif;max-width:720px;margin:0 auto;padding:32px 40px;color:#1e293b;font-size:14px}
  h1{font-size:20px;color:#312e81;margin:0 0 4px}
  .meta{font-size:12px;color:#64748b;margin-bottom:28px;border-bottom:2px solid #6366f1;padding-bottom:12px}
  .question{margin-bottom:24px;padding:16px;border:1px solid #e2e8f0;border-radius:8px;break-inside:avoid}
  .q-header{display:flex;align-items:flex-start;gap:10px;margin-bottom:10px}
  .q-num{background:#eef2ff;color:#4338ca;font-weight:700;font-size:12px;width:24px;height:24px;border-radius:50%;display:flex;align-items:center;justify-content:center;flex-shrink:0}
  .q-text{flex:1;font-weight:600;font-size:14px;line-height:1.5}
  .badge{font-size:9px;font-weight:700;background:#f1f5f9;color:#64748b;padding:2px 6px;border-radius:10px;text-transform:uppercase;flex-shrink:0}
  .options{display:grid;grid-template-columns:1fr 1fr;gap:6px;margin-left:34px}
  .opt{font-size:13px;padding:6px 10px;border-radius:6px;border:1px solid #e2e8f0}
  .opt.correct{background:#dcfce7;border-color:#86efac;color:#166534;font-weight:600}
  .explanation{margin-left:34px;margin-top:8px;font-size:12px;color:#64748b;background:#fafaf9;padding:8px 10px;border-radius:6px;border:1px solid #f1f0ef}
  .footer{margin-top:28px;padding-top:10px;border-top:1px solid #e2e8f0;font-size:11px;color:#94a3b8;text-align:center}
  @media print{body{padding:16px}}
</style></head><body>
<h1>${subject || "Class"} — Quiz${langNote}</h1>
<div class="meta">${grade ? grade + " · " : ""}${questions.length} questions · MCQ + True/False</div>
${items}
<div class="footer">Generated by Drishti</div>
</body></html>`;

  const win = window.open("", "_blank");
  if (!win) return;
  win.document.write(html);
  win.document.close();
  win.focus();
  setTimeout(() => { win.print(); }, 400);
}

const BLOOM_ORDER = ["remember","understand","apply","analyze","evaluate","create"];

function BloomBar({ level, count, total }: { level: string; count: number; total: number }) {
  const pct = total > 0 ? Math.round((count / total) * 100) : 0;
  return (
    <div className="flex items-center gap-2">
      <span className="w-20 text-xs text-slate-600 capitalize">{level}</span>
      <div className="flex-1 h-2 rounded-full bg-slate-100">
        <div
          className={cn("h-full rounded-full", BLOOM_COLOURS[level]?.split(" ")[0] ?? "bg-slate-300")}
          style={{ width: `${pct}%` }}
        />
      </div>
      <span className="w-6 text-right text-xs text-slate-500">{count}</span>
    </div>
  );
}

function MCQCard({ q, index }: { q: QuizQuestion; index: number }) {
  const [selected, setSelected] = useState<number | null>(null);
  const answered = selected !== null;

  return (
    <Card className="overflow-hidden">
      <CardHeader>
        <div className="flex items-start gap-3 w-full">
          <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-full bg-indigo-100 text-xs font-bold text-indigo-600">
            {index}
          </span>
          <p className="flex-1 text-sm font-medium text-slate-900">{q.text}</p>
        </div>
        <div className="flex gap-1 shrink-0">
          {q.bloom_level && (
            <Badge className={cn("text-[0.625rem]", BLOOM_COLOURS[q.bloom_level] ?? "bg-slate-100 text-slate-600")}>
              {q.bloom_level}
            </Badge>
          )}
          {q.topic && (
            <Badge variant="outline" className="text-[0.625rem] text-slate-500 border-slate-200">
              {q.topic}
            </Badge>
          )}
        </div>
      </CardHeader>
      <CardContent className="pt-0 space-y-2">
        {q.options?.map((opt, i) => {
          const isCorrect = i === q.correct;
          const isSelected = selected === i;
          return (
            <button
              key={i}
              onClick={() => !answered && setSelected(i)}
              className={cn(
                "w-full rounded-lg border px-4 py-2.5 text-left text-sm transition-all text-slate-700",
                !answered && "hover:border-indigo-300 hover:bg-indigo-50/40",
                answered && isCorrect && "border-green-500 bg-green-50 text-green-800 font-medium",
                answered && isSelected && !isCorrect && "border-red-400 bg-red-50 text-red-700",
                !answered ? "border-slate-200" : (!isCorrect && !isSelected ? "border-slate-100 text-slate-400" : "")
              )}
            >
              <span className="flex items-center gap-2">
                <span className="flex h-5 w-5 shrink-0 items-center justify-center rounded-full border text-xs">
                  {String.fromCharCode(65 + i)}
                </span>
                {opt}
                {answered && isCorrect && <CheckCircle2 className="ml-auto h-4 w-4 text-green-500" />}
                {answered && isSelected && !isCorrect && <XCircle className="ml-auto h-4 w-4 text-red-400" />}
              </span>
            </button>
          );
        })}
        {answered && (
          <p className="text-xs text-slate-500 pt-1">
            Correct answer: <strong>{q.options?.[q.correct as number]}</strong>
          </p>
        )}
      </CardContent>
    </Card>
  );
}

function TFCard({ q, index }: { q: QuizQuestion; index: number }) {
  const [selected, setSelected] = useState<boolean | null>(null);
  const answered = selected !== null;
  const correct = q.correct as boolean;

  return (
    <Card>
      <CardHeader>
        <div className="flex items-start gap-3 w-full">
          <span className="flex h-6 w-6 shrink-0 items-center justify-center rounded-full bg-purple-100 text-xs font-bold text-purple-600">
            {index}
          </span>
          <p className="flex-1 text-sm font-medium text-slate-900">{q.text}</p>
        </div>
        {q.bloom_level && (
          <Badge className={cn("text-[0.625rem] shrink-0", BLOOM_COLOURS[q.bloom_level] ?? "bg-slate-100")}>
            {q.bloom_level}
          </Badge>
        )}
      </CardHeader>
      <CardContent className="pt-0 flex gap-3">
        {[true, false].map(val => {
          const isCorrect = val === correct;
          const isSelected = selected === val;
          return (
            <button
              key={String(val)}
              onClick={() => !answered && setSelected(val)}
              className={cn(
                "flex-1 rounded-lg border py-3 text-sm font-medium transition-all",
                !answered && "hover:border-indigo-300 hover:bg-indigo-50/40",
                answered && isCorrect && "border-green-500 bg-green-50 text-green-700",
                answered && isSelected && !isCorrect && "border-red-400 bg-red-50 text-red-600",
                !answered ? "border-slate-200 text-slate-600" : (!isCorrect && !isSelected ? "border-slate-100 text-slate-300" : "")
              )}
            >
              {val ? "True ✓" : "False ✗"}
            </button>
          );
        })}
      </CardContent>
    </Card>
  );
}

export default function QuizPage({ params }: { params: Promise<{ sessionId: string }> }) {
  const { sessionId } = use(params);
  const { language, setLanguage, translating, translate, t } = useTranslation();

  const { data: quizData, isLoading, error } = useSWR(
    ["quiz", sessionId],
    () => api.getQuiz(sessionId),
    { shouldRetryOnError: false }
  );

  const { data: outputs } = useSWR(["outputs", sessionId], () => fetchOutputsCached(sessionId));
  const { data: session } = useSWR(["session", sessionId], () => api.getSession(sessionId), { revalidateOnFocus: false });
  const bloomOutput = outputs?.outputs?.bloom;
  const bloomCounts = bloomOutput?.data?.counts as Record<string, number> | undefined;
  const lowerOrder  = bloomOutput?.data?.lower_order_dominant as boolean | undefined;
  const suggestions = bloomOutput?.data?.suggestions as string[] | undefined;

  const questions = quizData?.questions ?? [];
  const mcqs   = questions.filter(q => q.type === "mcq");
  const trueFalse = questions.filter(q => q.type === "true_false");
  const totalBloom = bloomCounts ? Object.values(bloomCounts).reduce((a, b) => a + b, 0) : 0;

  useEffect(() => {
    if (!questions.length) return;
    const strings = [
      ...questions.map(q => q.text),
      ...questions.flatMap(q => q.options ?? []),
      ...(suggestions ?? []),
    ].filter(Boolean);
    translate(strings);
  }, [language, questions, suggestions, translate]);

  // Build translated question copies for rendering + PDF
  const tQuestions = questions.map(q => ({
    ...q,
    text: t(q.text),
    options: q.options ? q.options.map(o => t(o)) : null,
  }));
  const tMcqs      = tQuestions.filter(q => q.type === "mcq");
  const tTrueFalse = tQuestions.filter(q => q.type === "true_false");

  useEffect(() => {
    const handler = () => {
      if (questions.length === 0) return;
      downloadQuizPDF(tQuestions, session?.subject ?? "", session?.grade ?? "", language);
    };
    window.addEventListener("classroom-brain:download_pdf", handler);
    return () => window.removeEventListener("classroom-brain:download_pdf", handler);
  }, [questions, tQuestions, session, language]);

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-start justify-between flex-wrap gap-3">
        <div>
          <h1 className="text-xl font-bold text-slate-900">Quiz</h1>
          <p className="text-sm text-slate-500 mt-0.5">{questions.length} questions · MCQ + True/False</p>
        </div>
        <div className="flex items-center gap-2 flex-wrap">
          <LanguageSelector value={language} onChange={setLanguage} translating={translating} />
          {questions.length > 0 && (
            <button
              onClick={() => downloadQuizPDF(tQuestions, session?.subject ?? "", session?.grade ?? "", language)}
              className="flex items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-50 shadow-sm transition-colors"
            >
              <Download className="h-3.5 w-3.5" /> Download PDF
            </button>
          )}
          <Link href={`/sessions/${sessionId}/tiqer`}>
            <Button size="sm" variant="secondary">
              Export to TiQer <ChevronRight className="h-4 w-4" />
            </Button>
          </Link>
        </div>
      </div>

      {isLoading && <LoadingScreen label="Loading quiz…" />}
      {!isLoading && error && (
        <Empty
          icon={<HelpCircle className="h-12 w-12" />}
          title="Quiz not ready"
          description="Trigger AI generation from the Notes tab to generate quiz questions."
          action={
            <Link href={`/sessions/${sessionId}/notes`}>
              <Button size="sm" variant="secondary">Go to Notes →</Button>
            </Link>
          }
        />
      )}

      {!isLoading && questions.length > 0 && (
        <div className="grid gap-6 lg:grid-cols-3">
          {/* Bloom analysis sidebar */}
          <div className="lg:col-span-1 space-y-4">
            {bloomCounts && (
              <Card>
                <CardHeader>
                  <div className="flex items-center gap-2">
                    <BarChart2 className="h-4 w-4 text-indigo-600" />
                    <CardTitle>Bloom Distribution</CardTitle>
                  </div>
                </CardHeader>
                <CardContent className="space-y-2.5">
                  {BLOOM_ORDER.map(level => (
                    <BloomBar
                      key={level}
                      level={level}
                      count={bloomCounts[level] ?? 0}
                      total={totalBloom}
                    />
                  ))}
                  {lowerOrder && (
                    <div className="mt-3 flex items-start gap-2 rounded-lg bg-amber-50 p-3 text-xs text-amber-700">
                      <AlertTriangle className="h-3.5 w-3.5 shrink-0 mt-0.5" />
                      <span>Lower-order thinking dominates (&gt;60%). Add higher-order questions.</span>
                    </div>
                  )}
                </CardContent>
              </Card>
            )}

            {suggestions && suggestions.length > 0 && (
              <Card>
                <CardHeader><CardTitle className="text-sm">Suggested HOT Questions</CardTitle></CardHeader>
                <CardContent className="space-y-2">
                  {suggestions.map((s, i) => (
                    <div key={i} className="rounded-lg bg-indigo-50 p-3 text-xs text-indigo-800">
                      {t(s)}
                    </div>
                  ))}
                </CardContent>
              </Card>
            )}

            {/* Quick stats */}
            <Card>
              <CardContent className="space-y-3">
                <div className="flex justify-between text-sm">
                  <span className="text-slate-500">MCQ</span>
                  <span className="font-semibold">{mcqs.length}</span>
                </div>
                <div className="flex justify-between text-sm">
                  <span className="text-slate-500">True/False</span>
                  <span className="font-semibold">{trueFalse.length}</span>
                </div>
                <div className="flex justify-between text-sm">
                  <span className="text-slate-500">Total</span>
                  <span className="font-bold text-indigo-600">{questions.length}</span>
                </div>
              </CardContent>
            </Card>
          </div>

          {/* Questions */}
          <div className="lg:col-span-2 space-y-4">
            {tMcqs.length > 0 && (
              <>
                <h2 className="text-sm font-semibold text-slate-500 uppercase tracking-wide">
                  MCQ Questions
                </h2>
                {tMcqs.map((q, i) => <MCQCard key={q.id} q={q} index={i + 1} />)}
              </>
            )}
            {tTrueFalse.length > 0 && (
              <>
                <h2 className="mt-4 text-sm font-semibold text-slate-500 uppercase tracking-wide">
                  True / False
                </h2>
                {tTrueFalse.map((q, i) => <TFCard key={q.id} q={q} index={tMcqs.length + i + 1} />)}
              </>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
